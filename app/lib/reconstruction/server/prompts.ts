import { type ReconstructionHints, type DrawingAnalysis } from "../types";
function describeHints(hints: ReconstructionHints) {
  const unit = hints.unit || "единица не подтверждена";
  return [
    `единицы=${unit}`,
    `режим=${hints.allowInferredGeometry === false ? "только доказанные размеры" : "ИИ самостоятельно восстанавливает неизвестное как черновое допущение"}`,
    hints.width ? `ширина=${hints.width} ${unit}` : "",
    hints.height ? `высота=${hints.height} ${unit}` : "",
    hints.depth ? `глубина=${hints.depth} ${unit}` : "",
  ]
    .filter(Boolean)
    .join(", ");
}

function inferencePolicy(hints: ReconstructionHints) {
  if (hints.allowInferredGeometry === false) {
    return `СТРОГИЙ РЕЖИМ: используй только размеры и форму, доказанные пользователем, размерными надписями, CAD-координатами или согласованными видами. Не подставляй типовые значения. Неизвестное оставляй в unresolved.`;
  }
  return `РЕЖИМ САМОСТОЯТЕЛЬНОЙ AI-РЕКОНСТРУКЦИИ: цель — построить наиболее вероятный полный 3D-черновик даже при неполных исходных данных.
- Самостоятельно выбирай конструктивно наиболее вероятный вариант по симметрии, повторяющимся модулям, размерным цепочкам, согласованию проекций, пропорциям и типовой логике показанного объекта. Не задавай пользователю вопрос вместо построения.
- Если допустимы несколько вариантов, выбери самый простой и консервативный, который согласуется со всеми видимыми данными; отклонённые варианты кратко перечисли в warnings.
- Каждый восстановленный размер добавляй в dimensions с source=inferred и confidence не выше 0.65. В evidence каждой детали, зависящей от него, добавляй строку «AI-допущение: …» с причиной выбора. Уверенность такой детали не должна быть выше 0.65.
- Не скрывай неопределённость: сохрани соответствующий unresolved, верни status=needs_input и canExport=false. Допущение разрешает построить черновик, но не превращается в доказанный факт.
- parts обязан быть непустым, когда на листе виден связный объект и можно определить единицы либо разумный технический масштаб. При неизвестных единицах используй mm только как техническую единицу черновика и предупреди об этом.`;
}

export function buildAnalysisPrompt(
  sourceName: string,
  context: string,
  hints: ReconstructionHints,
) {
  return `Выполни первый этап: метрологический аудит технического чертежа «${sourceName}». Пока не строй 3D.

1. Сначала определи ПОЛНЫЙ ОБЪЕКТ по основной надписи и заголовку листа, затем тип листа и все согласованные виды: главный, сверху, сбоку, разрезы, выносные и изометрические виды. В CAD documentIdentity.titleCandidates имеет приоритет для objectName. documentIdentity.repeatedComponentLabels — локальные повторяющиеся подписи компонентов; запрещено принимать такую подпись за название всего объекта.
2. Перепиши только читаемые числовые размеры без округления. Укажи источник: drawing для размерной надписи, cad для точной CAD-координаты, user для подтверждённого ввода, inferred только для логического вывода с confidence не выше 0.8.
3. Выдели формообразующие элементы: основные тела, вырезы, отверстия, пазы, фаски, скругления, массивы и оси. Для каждого приведи видимое доказательство.
4. Сделай явные выводы о соответствии проекций друг другу. Не считай одинаковые линии одним элементом без согласования минимум по двум видам или разрезу.
5. Любой скрытый размер, масштаб, количество повторов или внутренняя поверхность без доказательства должны попасть в unresolved. Если неизвестны единицы, верни unit=unknown и критическую неопределённость.
6. sufficientFor3d=true разрешено только когда единицы, общий масштаб и все размеры, влияющие на итоговую форму, доказаны. Перспективное изображение без размеров всегда недостаточно.
7. Для CAD-контекста V3 расшифруй сокращения по entitySchema. Обязательно прочитай Paper/Layout Space (s=p:...) как основную надпись и названия видов, но не превращай рамку листа в геометрию объекта. На этапе аудита переданы точные размеры, подписи, вставки и полные сводки типов/областей; детальная векторная геометрия будет передана следующему этапу построения.
8. Если напечатанный размер display/nominal отличается от геометрического anchorMeasurement, считай напечатанное число проектным номиналом, а расхождение — предупреждением для проверки. Приоритет: подтверждённые данные пользователя, напечатанный номинал, CAD-геометрия, затем растр.
9. Приложения идут так: обзор всего листа, затем увеличенные фрагменты слева направо и сверху вниз. Используй фрагменты для мелкого текста и контуров, обзор — для связи видов.
10. Отчёт должен быть компактным и без повторов: верни до 16 формообразующих dimensions, 10 features, 8 conclusions и 6 unresolved. Для feature/conclusion оставляй одно самое сильное evidence, каждое текстовое поле формулируй одним коротким предложением. Повторяющиеся одинаковые размеры группируй; полный машинный CAD-паспорт остаётся доступен этапу построения.

${inferencePolicy(hints)}
На этапе аудита AI-допущения не делают sufficientFor3d=true: это поле отражает только доказанность производственной геометрии.

Подтверждённые пользователем данные: ${describeHints(hints)}.
Комментарий пользователя: ${hints.notes || "нет"}.
Машинно извлечённый CAD-контекст:
${context || "нет — анализируй только изображение"}`;
}

export function buildModelPrompt(
  sourceName: string,
  analysis: DrawingAnalysis,
  context: string,
  hints: ReconstructionHints,
) {
  return `Выполни второй этап: построй проверяемую параметрическую 3D-модель объекта «${sourceName}» по приложенному AI-аудиту и исходному чертежу.

AI-аудит является исходной гипотезой, которую нужно сверить с основной надписью, documentIdentity и CAD-геометрией. Если objectName аудита совпал с repeatedComponentLabels, исправь замысел модели по titleCandidates и строй весь объект, а не отдельный компонент:
${JSON.stringify(analysis)}

Машинно извлечённый CAD-контекст:
${context || "нет"}

Система координат: X — ширина слева направо, Y — высота вверх, Z — глубина от фронта назад. Position — центр детали. Для box используй size X/Y/Z. Для cylinder используй radius и height, ось Y. Для extrusion профиль задаётся точками X/Z, height идёт по Y, сквозные отверстия — контурами holes. Для осесимметричной детали используй revolution: profile.x — радиус, profile.z — положение вдоль оси.

Используй обзор и ВСЕ увеличенные фрагменты для трассировки контуров. Приоритет доказательств: user, основная надпись для идентичности объекта, напечатанный nominal/display, CAD-координаты, затем растр. Для s=b:<name> примени INSERT/MINSERT. Учитывай bulge, дуги, окружности, эллипсы, сплайны, границы HATCH, thickness, elevation, extrusionDirection, слои, handle и пространственные области. Не создавай mesh: сетка допустима только из прямой CAD-геометрии.

Инженерные ограничения геометрии:
- HATCH — это обозначение материала или сечения, а не отдельное твёрдое тело. Не создавай part только из имени/границы штриховки без подтверждающего контура детали.
- Не переноси общий габарит листа или всего объекта на локальную деталь. Каждый size должен соответствовать физическому размеру именно этой детали; неизвестную толщину помечай AI-допущением.
- Повторяющиеся стойки, колонны и опоры моделируй отдельными частями в доказанных координатах. Не заменяй массив одной сплошной коробкой на всю длину объекта.
- Сначала составь иерархию: весь объект → крупные узлы → отдельные конструктивные элементы. Локальная подпись элемента никогда не заменяет весь объект.
- После построения мысленно спроецируй модель на каждый обнаруженный вид. Если силуэт, число опор, лестниц, площадок, отверстий или осей не совпадает, исправь parts до ответа.
- Все названия, выводы, предупреждения и основания пиши по-русски.

${inferencePolicy(hints)}

Если sufficientFor3d=false, обязательно верни status=needs_input и canExport=false, но построй максимально полный предварительный объект в пределах выбранного режима. Если unit=unknown, используй mm лишь как техническую единицу предварительного результата и не разрешай экспорт. Перенеси только уникальные формообразующие unresolved из аудита. Каждая часть обязана иметь одно короткое evidence со ссылкой на размер, вид, handle, вывод аудита или явно помеченное AI-допущение. Используй столько отдельных частей, сколько нужно для сохранения топологии, но не более 28; разрешено объединять только физически непрерывный элемент одного сечения. Не повторяй detectedViews и dimensions: для них схема требует пустые массивы.`;
}

