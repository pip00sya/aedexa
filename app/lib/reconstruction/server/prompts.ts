export function buildTopologyRepairPrompt(
  sourceName: string,
  analysis: DrawingAnalysis,
  context: string,
  hints: ReconstructionHints,
  candidateModel: Record<string, unknown>,
) {
  return `Первый 3D-проход объекта «${sourceName}» потерял крупные узлы или схлопнул их в общие коробки. Верни ПОЛНУЮ замену модели, а не список исправлений.

Проверенный аудит:
${JSON.stringify(analysis)}

Неполная модель:
${JSON.stringify(candidateModel)}

CAD-контекст V3:
${context || "нет"}

Правила восстановления топологии:
- Каждому feature с kind=solid сопоставь хотя бы одну физическую part. Повторяемые левый/правый узлы должны быть отдельными частями.
- Для объекта с шестью и более крупными узлами верни не меньше восьми ненулевых частей: пролёт/настил, крыша или ограждение при наличии, опоры, площадки, лестничные/эскалаторные марши, лифтовые шахты и фундаменты.
- Общая длина пролёта задаёт только продольную ось соответствующего элемента. Клиренс над дорогой задаёт высоту положения, а ширина дороги или фундамента не является толщиной либо глубиной настила.
- Не создавай box с общими X/Y/Z габаритами всего сооружения. size каждой части — её собственные физические размеры; position — её центр.
- Для наклонного марша допустим повёрнутый box с ненулевой толщиной и шириной, для площадки — отдельный box. Никаких нулевых размеров.
- Не ставь одинаковый поворот 90° всем частям. Горизонтальный пролёт и площадки обычно имеют rotationDegrees=0; наклон задаётся только конкретным лестничным/эскалаторным маршам.
- Сверь количество и расположение частей с главным видом, планом и обоими фасадами. detectedViews и dimensions верни пустыми массивами; одно короткое evidence на часть.

${inferencePolicy(hints)}
Если часть восстановлена по симметрии или пропорциям, пометь evidence как «AI-допущение», confidence не выше 0.65, status=needs_input и canExport=false.`;
}

export function buildReviewPrompt(
  sourceName: string,
  context: string,
  hints: ReconstructionHints,
  initialAnalysis: DrawingAnalysis,
  candidateModel: Record<string, unknown>,
) {
  return `Проведи независимую инженерную приёмку реконструкции объекта «${sourceName}» и верни только компактный протокол проверки. Не повторяй целиком analysis, model или parts.

Ожидаемый результат: геометрия должна совпадать с исходным чертежом во всех видимых проекциях и содержать только доказанные элементы. Не подтверждай черновик автоматически — заново прочитай исходный лист.

${inferencePolicy(hints)}

Критерии приёмки:
- Начни проверку заново с основной надписи. documentIdentity.titleCandidates определяет весь объект, repeatedComponentLabels — его локальные компоненты. Исправь analysis.objectName, model.title и всю топологию, если первичный аудит перепутал компонент с объектом.
- Сверь главный вид, вид сверху, боковые виды, разрезы, выносные элементы, скрытые линии и оси. Один контур не подтверждает глубину или внутреннюю форму без второго вида, разреза либо числового размера.
- Повторно распознай все читаемые размеры и единицы. Данные пользователя имеют источник user и приоритет; точные CAD-координаты имеют источник cad. Не измеряй размеры по пикселям, если масштаб явно не задан.
- В CAD-контексте V3 расшифруй entitySchema, проверь все пространственные области и типы сущностей. Для s=b:<name> примени соответствующий INSERT/MINSERT. Сверяй handle и layer. Приоритет: user, напечатанный nominal/display, CAD-геометрия, растр; конфликт nominal и anchorMeasurement является предупреждением, а не причиной удалить доказанную геометрию.
- Проверь каждую часть модели: вид тела, положение центра, поворот, размеры X/Y/Z, радиус, высоту, профиль, отверстия, пазы, фаски, скругления, симметрию и количество повторов. Числовые ошибки существующей части верни в corrections; полностью ложные части перечисли в rejectedPartIds.
- Спроецируй итоговую модель на каждый обнаруженный вид и сравни силуэты, оси, размерные цепочки и количество повторов. Набор больших коробок, повторяющих общий габарит объекта вместо отдельных узлов, приёмку не проходит.
- Модель уже приведена к X — длина, Y — высота, Z — глубина. Одинаковый поворот 90° у всех частей является ошибкой. Парные «левый/правый» части не могут полностью совпадать по position. Фундамент опор не может быть одной плитой длиной во весь пролёт, если на виде показаны раздельные основания.
- Проверь систему координат: X — ширина, Y — высота, Z — глубина. Для box size задаёт X/Y/Z; cylinder направлен по Y; extrusion выдавливается по Y; revolution задаётся профилем радиус/ось.
- Не создавай mesh. В строгом режиме не придумывай невидимую геометрию. В AI-режиме допускается наиболее вероятная невидимая геометрия только с явной пометкой «AI-допущение», confidence не выше 0.65 и заблокированным производственным экспортом. Если формообразующий размер не доказан, оставь его критической неопределённостью, status=needs_input, sufficientFor3d=false и canExport=false.
- Если черновая модель содержит хотя бы одну размеренную часть, не заменяй весь parts пустым массивом. Исправь ошибочные части, удали только недоказанные и сохрани хотя бы одну доказанную часть; понизь status/canExport вместо уничтожения проверяемого черновика.
- Удали неопределённость только когда её действительно закрывает размер, согласованный вид, разрез, CAD-координата или подтверждённый ввод пользователя.
- Калибруй уверенность по доказательствам: 1.0 допустимо только для точной CAD-геометрии; 0.95–0.99 — для полностью размеренного и согласованного многовидового чертежа; 0.85–0.94 — только при мелкой неопределённости, не влияющей на форму; при неизвестном формообразующем размере итог должен быть ниже 0.85. Не повышай число ради красивого результата.
- accepted=true только если ни одна критическая ошибка не влияет на видимую форму. В unresolved верни только новые уникальные проблемы, в warnings — только краткие замечания. objectName снова определи по основной надписи. Не переписывай геометрию: corrections содержит только изменённые числовые параметры существующих частей.

Подтверждённые пользователем данные: ${describeHints(hints)}.
Комментарий пользователя: ${hints.notes || "нет"}.
Машинно извлечённый CAD-контекст:
${context || "нет"}

Первичный аудит, который нужно проверить и при необходимости исправить:
${JSON.stringify(initialAnalysis)}

Черновая 3D-модель, которую нужно проверить и при необходимости перестроить:
${JSON.stringify(candidateModel)}`;
}
